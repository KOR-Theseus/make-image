import { promises as fs } from "node:fs";
import path from "node:path";
import { slugify, buildRunId } from "./naming.js";

export function hashNumber(text) {
  let hash = 2166136261;
  for (const char of String(text || "")) {
    hash ^= char.charCodeAt(0);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

export function createObjBuilder() {
  const objects = [];

  function addBox(name, center, size, material, group = name) {
    const [cx, cy, cz] = center;
    const [sx, sy, sz] = size.map((value) => value / 2);
    const points = [
      [cx - sx, cy - sy, cz - sz], [cx + sx, cy - sy, cz - sz], [cx + sx, cy + sy, cz - sz], [cx - sx, cy + sy, cz - sz],
      [cx - sx, cy - sy, cz + sz], [cx + sx, cy - sy, cz + sz], [cx + sx, cy + sy, cz + sz], [cx - sx, cy + sy, cz + sz]
    ];
    objects.push({
      name,
      group,
      material,
      points,
      faces: [
        [1, 2, 3, 4],
        [5, 8, 7, 6],
        [1, 5, 6, 2],
        [2, 6, 7, 3],
        [3, 7, 8, 4],
        [4, 8, 5, 1]
      ]
    });
  }

  function toObj(selectedObjects = objects) {
    const lines = ["# Generated by Codex Image Generator 3D export", "mtllib asset.mtl"];
    let vertexOffset = 0;
    for (const object of selectedObjects) {
      lines.push(`o ${object.name}`);
      for (const point of object.points) lines.push(`v ${point.map((value) => value.toFixed(4)).join(" ")}`);
      lines.push(`usemtl ${object.material}`);
      for (const face of object.faces) lines.push(`f ${face.map((index) => index + vertexOffset).join(" ")}`);
      vertexOffset += object.points.length;
    }
    return `${lines.join("\n")}\n`;
  }

  return {
    addBox,
    objects,
    groups() {
      return [...new Set(objects.map((object) => object.group))];
    },
    toObj,
    toGroupObj(group) {
      return toObj(objects.filter((object) => object.group === group));
    }
  };
}

export function makeMtl() {
  return [
    ["grass", "0.21 0.55 0.24"],
    ["soil", "0.34 0.22 0.13"],
    ["bark", "0.31 0.18 0.09"],
    ["leaf", "0.08 0.36 0.16"],
    ["leaf_light", "0.18 0.52 0.22"],
    ["stone", "0.43 0.45 0.46"],
    ["water", "0.12 0.48 0.75"],
    ["fire", "1.00 0.28 0.04"],
    ["obsidian", "0.06 0.05 0.05"]
  ].map(([name, color]) => [
    `newmtl ${name}`,
    `Kd ${color}`,
    "Ka 0.02 0.02 0.02",
    "Ks 0.12 0.12 0.12",
    "Ns 32"
  ].join("\n")).join("\n\n");
}

export function buildForestTerrainMesh(prompt, settings = {}) {
  const seed = hashNumber(`${prompt}:${settings.meshAssetKind}`);
  const size = Math.max(8, Math.min(48, Number(settings.meshTileSize || 24)));
  const builder = createObjBuilder();
  builder.addBox("terrain_base", [0, -0.32, 0], [size, 0.6, size], "soil", "terrain_block");
  builder.addBox("grass_cap", [0, 0.02, 0], [size, 0.12, size], "grass", "terrain_block");

  const cells = 7;
  const step = size / cells;
  for (let row = 0; row < cells; row += 1) {
    for (let col = 0; col < cells; col += 1) {
      const value = (seed + row * 37 + col * 71) % 11;
      const x = -size / 2 + step / 2 + col * step;
      const z = -size / 2 + step / 2 + row * step;
      if (value < 5) {
        const trunkHeight = 1.6 + (value % 3) * 0.35;
        const group = `tree_${row}_${col}`;
        builder.addBox(`${group}_trunk`, [x, trunkHeight / 2, z], [0.32, trunkHeight, 0.32], "bark", group);
        builder.addBox(`${group}_leaves_low`, [x, trunkHeight + 0.55, z], [1.35, 1.1, 1.35], value % 2 ? "leaf" : "leaf_light", group);
        builder.addBox(`${group}_leaves_top`, [x, trunkHeight + 1.25, z], [0.9, 0.85, 0.9], "leaf", group);
      } else if (value < 7) {
        builder.addBox(`rock_${row}_${col}`, [x, 0.25, z], [0.85, 0.5, 0.65], "stone", `rock_${row}_${col}`);
      }
    }
  }

  if (String(prompt).toLowerCase().includes("water") || String(prompt).toLowerCase().includes("river")) {
    builder.addBox("river_strip", [0, 0.11, 0], [size * 0.18, 0.08, size], "water", "river_strip");
  }
  return builder;
}

export function buildElementalBlockMesh(prompt) {
  const builder = createObjBuilder();
  const isWater = /water|aqua|river|sea/i.test(prompt);
  const core = isWater ? "water" : "obsidian";
  const accent = isWater ? "water" : "fire";
  builder.addBox("core_body", [0, 1.25, 0], [1.4, 2.1, 0.85], core, "body");
  builder.addBox("head", [0, 2.65, 0], [1.1, 1.1, 1.1], core, "head");
  builder.addBox("left_arm", [-1.0, 1.55, 0], [0.55, 1.55, 0.55], accent, "left_arm");
  builder.addBox("right_arm", [1.0, 1.55, 0], [0.55, 1.55, 0.55], accent, "right_arm");
  builder.addBox("left_leg", [-0.42, 0.25, 0], [0.48, 0.9, 0.48], accent, "left_leg");
  builder.addBox("right_leg", [0.42, 0.25, 0], [0.48, 0.9, 0.48], accent, "right_leg");
  builder.addBox("head_crest", [0, 3.4, 0], [0.7, 0.75, 0.7], accent, "head");
  return builder;
}

export async function exportMeshAsset({ prompt, settings, outputDir, publicUrlForGenerated }) {
  const kind = settings.meshAssetKind || "forest-terrain";
  const promptSlug = slugify(prompt, "mesh");
  const exportId = buildRunId("mesh", prompt, kind);
  const outDir = path.join(outputDir, "meshes", exportId);
  await fs.mkdir(outDir, { recursive: true });

  const builder = kind === "elemental-block-character"
    ? buildElementalBlockMesh(prompt, settings)
    : buildForestTerrainMesh(prompt, settings);
  const objPath = path.join(outDir, "asset.obj");
  const mtlPath = path.join(outDir, "asset.mtl");
  await fs.writeFile(objPath, builder.toObj());
  await fs.writeFile(mtlPath, makeMtl());

  const componentsDir = path.join(outDir, "components");
  await fs.mkdir(componentsDir, { recursive: true });
  await fs.writeFile(path.join(componentsDir, "asset.mtl"), makeMtl());
  const components = [];
  for (const group of builder.groups()) {
    const fileName = `${slugify(group, "component")}.obj`;
    const componentPath = path.join(componentsDir, fileName);
    await fs.writeFile(componentPath, builder.toGroupObj(group));
    components.push({
      name: group,
      path: componentPath,
      url: publicUrlForGenerated(componentPath),
      objectCount: builder.objects.filter((object) => object.group === group).length
    });
  }

  const manifest = {
    id: exportId,
    prompt,
    promptSlug,
    kind,
    objPath,
    objUrl: publicUrlForGenerated(objPath),
    mtlPath,
    mtlUrl: publicUrlForGenerated(mtlPath),
    componentsDir,
    componentsUrl: publicUrlForGenerated(componentsDir),
    components,
    format: "obj",
    note: "OBJ/MTL export completed. Unity can import static OBJ meshes directly.",
    createdAt: new Date().toISOString()
  };
  await fs.writeFile(path.join(outDir, "manifest.json"), JSON.stringify(manifest, null, 2));
  return manifest;
}
